"""Training settings. Defaults are what the dissertation actually ran, read from its code
and saved training_args.bin; several differ from the report (see the README)."""

from dataclasses import dataclass, replace

from biomedical_qa_peft.evaluation.config import BASELINE_PROMPT


@dataclass(frozen=True)
class TrainingConfig:
    """Prefix-tuning settings; LORA_TRAINING below lists LoRA's differences."""

    num_train_epochs: float = 3
    # 2 x 2 = effective batch 4, as in the saved training_args.bin (the notebook showed 4).
    per_device_train_batch_size: int = 2
    per_device_eval_batch_size: int = 4
    gradient_accumulation_steps: int = 2
    optim: str = "adamw_torch"
    learning_rate: float = 2e-5
    weight_decay: float = 0.01
    warmup_steps: int = 50
    lr_scheduler_type: str = "linear"
    fp16: bool = True
    # Evaluate and checkpoint every 250 steps; keep the best by validation loss and stop
    # after 2 evaluations without improvement.
    eval_steps: int = 250
    save_steps: int = 250
    save_total_limit: int = 2
    early_stopping_patience: int = 2
    logging_steps: int = 100
    # Throughput and memory settings from the original.
    dataloader_num_workers: int = 2
    group_by_length: bool = True
    torch_empty_cache_steps: int = 4
    activation_checkpointing: bool = False  # Called gradient checkpointing before transformers 5.
    seed: int = 42


# LoRA's saved training_args.bin: 4 x 2 = effective batch 8 (1,000 steps per epoch),
# with gradient checkpointing; everything else as for prefix tuning.
LORA_TRAINING = replace(TrainingConfig(), per_device_train_batch_size=4, activation_checkpointing=True)


@dataclass(frozen=True)
class PrefixConfig:
    num_virtual_tokens: int = 20
    # The prefix is generated by a trained MLP (hidden size wide) during training; only
    # its output, 20 x (layers x 2 x KV dim) values, is saved.
    prefix_projection: bool = True
    # Replaces the dataset's system prompt, in training as at test time.
    system_prompt: str = BASELINE_PROMPT


@dataclass(frozen=True)
class LoraSettings:
    # Rank-8 adapters on the attention query and value projections.
    r: int = 8
    lora_alpha: int = 16
    lora_dropout: float = 0.05
    target_modules: tuple[str, ...] = ("q_proj", "v_proj")
    system_prompt: str = BASELINE_PROMPT
